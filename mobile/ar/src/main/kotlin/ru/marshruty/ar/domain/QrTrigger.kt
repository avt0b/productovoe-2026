package ru.marshruty.ar.domain

/**
 * QR-код как способ вызвать проводника.
 *
 * Табличка-картинка даёт точную позу, но требовательна: ей нужен свет, ровная
 * поверхность и пара секунд движения камерой. На защите и в музейном зале
 * этого не всегда хватает, а проводник должен появляться наверняка. QR-код
 * читается почти мгновенно, с экрана телефона, с мятой бумаги и под углом —
 * поэтому он и служит запасным ключом: увидели код — проводник выходит сразу,
 * не дожидаясь, пока ARCore разберёт картинку.
 *
 * Точность при этом теряется: QR говорит «код в кадре», но не говорит, где он
 * в мире. Поэтому проводник встаёт перед человеком, а не на табличку.
 */

/**
 * Подходит ли прочитанный код.
 *
 * `expected == null` — подходит любой: на точке без своего кода проводника
 * вызывает что угодно, вплоть до кода с чужого билета. Это осознанно: пустой
 * экран хуже, чем проводник, вызванный не тем кодом.
 *
 * Сравнение — по точному совпадению без учёта регистра и внешних пробелов:
 * коды печатают из разных источников, и лишний перевод строки в конце не
 * должен решать, выйдет проводник или нет.
 */
fun qrTriggersCompanion(expected: String?, scanned: String?): Boolean {
    val code = scanned?.trim().orEmpty()
    if (code.isEmpty()) return false
    val wanted = expected?.trim().orEmpty()
    if (wanted.isEmpty()) return true
    return code.equals(wanted, ignoreCase = true)
}
