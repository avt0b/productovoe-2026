import type { RouteRecordRaw } from 'vue-router'

/**
 * Модуль приложения — одно окно или группа связанных окон.
 *
 * Модуль ничего не знает о других модулях и о том, как собрано приложение:
 * он отдаёт свои роуты и, если он раздел, вкладку в нижней панели. Приложение
 * находит модули само (`src/app/registry.ts`), поэтому:
 *
 * - добавить окно — положить папку `src/modules/<окно>/` с `index.ts`;
 * - убрать окно — удалить папку или выставить `enabled: false`.
 *
 * Центрального списка модулей нет намеренно: окна делаются отдельными PR,
 * и общий файл со списком конфликтовал бы в каждом из них.
 */
export interface AppModule {
  /** Уникальный идентификатор. Удобно брать имя папки. */
  id: string
  /** `false` — модуль лежит в коде, но в приложение не попадает. */
  enabled?: boolean
  routes: RouteRecordRaw[]
  tab?: ModuleTab
}

/** Раздел в нижней панели навигации. */
export interface ModuleTab {
  title: string
  /** Имя иконки Material Symbols. */
  icon: string
  /** Имя роута, на который ведёт вкладка. */
  route: string
  /** Порядок слева направо. Шаг 10 — чтобы новый раздел встал между соседями без перенумерации. */
  order: number
}

/** Обёртка ради вывода типов в `index.ts` модуля. */
export function defineModule(module: AppModule): AppModule {
  return module
}

declare module 'vue-router' {
  interface RouteMeta {
    /** Каркас экрана: с вкладками, детальный с кнопкой «Назад» или голый. По умолчанию `tabs`. */
    layout?: 'tabs' | 'detail' | 'bare'
    /** Заголовок в шапке. */
    title?: string
    /** Экран открыт без входа. */
    public?: boolean
    /**
     * Это экран входа. Если ни один модуль такой экран не объявил, приложение
     * открывается без авторизации — модуль входа можно убрать целиком.
     */
    auth?: boolean
    /** Какую вкладку подсвечивать, если экран сам не вкладка (например, карточка точки). */
    tab?: string
  }
}
