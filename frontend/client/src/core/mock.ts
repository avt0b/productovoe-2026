/**
 * Задержка для заглушек данных.
 *
 * Мгновенный ответ прятал бы состояния загрузки: экран, у которого спиннер ни
 * разу не появлялся, первым же медленным запросом к настоящему сервису
 * покажет белую пустоту. Треть секунды — достаточно, чтобы их было видно.
 */
export function withLatency<T>(value: T, ms = 350): Promise<T> {
  return new Promise((resolve) => setTimeout(() => resolve(value), ms))
}
