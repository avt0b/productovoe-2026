/**
 * Демо-набор Орловской области — на случай, когда сервисы не отвечают.
 *
 * Это зеркало того, что заливают `scripts/seed_orel.py` в `map_service` и
 * `route_service`: те же места, тексты и **те же id** (uuid5). Поэтому ссылка
 * «маршрут → точка» ведёт в одно и то же место и с сервером, и без него.
 * Меняете демо в бэкенде — поменяйте и здесь.
 *
 * Слой «ВОВ» — реальные места (координаты мемориалов Орла из OpenStreetMap,
 * у сёл и городов — координаты населённого пункта). «Последний бой» — демо по
 * сценариям кейса, `source` начинается с «ДЕМО».
 */

