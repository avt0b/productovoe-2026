import type { GeoTone, LatLon } from '@/core/geo'

/**
 * Окружность на карте: радиус вокруг точки.
 *
 * Нужна там, где важно не само место, а расстояние до него: «в 5 км от вас
 * обнаружено место гибели бойца», зона поисковых работ, радиус сбора группы.
 * Тип лежит в UI-ките, а не в `core/geo`: это способ нарисовать, а не знание
 * о предметной области.
 */
export interface GeoCircle extends LatLon {
  id: string
  /** Радиус в метрах. */
  radiusMeters: number
  /** Цвет по роли: `primary` — важное, `secondary` — полевое, `tertiary` — наградное. */
  tone?: GeoTone
  /** Пунктиром — граница приблизительная («где-то в этом круге»). */
  dashed?: boolean
}
