/**
 * Совёнок-следопыт — проводник по приложению.
 *
 * Картинки лежат в `public/mascot/<поза>.png`: их выбирают по имени в разметке
 * и в данных обучения, поэтому в `src/assets` с хешированными именами им
 * делать нечего. Позы — закрытый список: опечатка в имени дала бы на экране
 * битую картинку вместо подсказки.
 *
 * Не путать с проводником AR (`features/ar`): там трёхмерный пёс Верный,
 * который встаёт на табличку в кадре. Совёнок живёт только в интерфейсе.
 */
export const MASCOT_POSES = [
  /** Машет крылом: приветствие. */
  'wave',
  /** Отдаёт честь: знакомство и благодарность. */
  'salute',
  /** Показывает крылом в сторону: «смотрите сюда». */
  'point',
  /** Рассказывает, крыло поднято: объяснение. */
  'explain',
  /** Разводит крылом: представляет раздел. */
  'present',
  /** С лупой: поиск и фильтры. */
  'search',
  /** С развёрнутой картой: маршруты и места. */
  'map',
  /** С карманными часами: время, расписание, ожидание. */
  'watch',
  /** Задумался: выбор и сомнение. */
  'think',
  /** Со знаком вопроса: пусто, не нашлось, непонятно. */
  'question',
  /** За ноутбуком: заполнить форму, завести своё. */
  'laptop',
  /** Прыгает с конфетти: награда и «готово». */
  'celebrate',
] as const

export type MascotPose = (typeof MASCOT_POSES)[number]

export function mascotSrc(pose: MascotPose): string {
  return `/mascot/${pose}.png`
}

/**
 * Подгрузить картинку заранее.
 *
 * В обучении шаги листают подряд, и без этого на каждом шаге маскот появлялся
 * бы с задержкой: картинка начинает грузиться только когда её вставили в
 * разметку. Сбои игнорируем — это подсказка, а не содержимое экрана.
 */
export function preloadMascot(pose: MascotPose): void {
  if (typeof Image === 'undefined') return
  const image = new Image()
  image.src = mascotSrc(pose)
}
