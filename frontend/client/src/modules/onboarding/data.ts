/** Первой — та глава, ради которой роль выдана; остальные в обычном порядке. */
const ORDER: Partial<Record<UserRole, readonly string[]>> = {
  searcher: ['start', 'last-stand', 'hq', 'memory', 'routes', 'route-point', 'excursions', 'profile'],
  local_historian: ['start', 'excursions', 'routes', 'route-point', 'memory', 'last-stand', 'hq', 'profile'],
}

function visible(step: TourStep, role: UserRole, familyMode: boolean): boolean {
  if (step.roles && !step.roles.includes(role)) return false
  if (step.familyOnly && !familyMode) return false
  // Пара «значки» и «значки со званием»: вторая — замена первой вне семейного
  // режима, иначе про значки рассказали бы дважды подряд.
  if (step.id === 'prof-badges-plain' && familyMode) return false
  return true
}

/**
 * Главы под конкретного человека: лишние шаги сняты, порядок — от роли.
 *
 * Роль не выбрана (демо-режим) — рассказываем как семье: так приложение и
 * работает, пока заявку не подтвердили.
 */
export function chaptersFor(role: UserRole | undefined, familyMode: boolean): Chapter[] {
  const actual = role ?? 'family'
  const filtered = CHAPTERS.map((chapter) => ({
    ...chapter,
    steps: chapter.steps.filter((step) => visible(step, actual, familyMode)),
  })).filter((chapter) => chapter.steps.length > 0)

  const order = ORDER[actual]
  const ordered = order
    ? [
        ...order.flatMap((id) => {
          const chapter = filtered.find((item) => item.id === id)
          return chapter ? [chapter] : []
        }),
        ...filtered.filter((chapter) => !order.includes(chapter.id)),
      ]
    : filtered

  return [...ordered, finaleFor(actual)]
}

/** Разделы приложения — те главы, у которых есть свой экран. Их шесть, как вкладок внизу. */
export function tabChapters(chapters: readonly Chapter[]): Chapter[] {
  return chapters.filter((chapter) => chapter.route !== null)
}

/** Главы для шпаргалки: без последней, которая имеет смысл только в конце обучения. */
export function guideChapters(chapters: readonly Chapter[]): Chapter[] {
  return chapters.filter((chapter) => !chapter.tourOnly)
}

/** Шаг обучения вместе с главой, из которой он пришёл. */
export interface TourEntry {
  chapter: Chapter
  step: TourStep
  /** Который это шаг главы и сколько их — для точек прогресса. */
  index: number
  total: number
}

/** Главы — в одну ленту шагов: обучение листают подряд, а не по главам. */
export function flatten(chapters: readonly Chapter[]): TourEntry[] {
  return chapters.flatMap((chapter) =>
    chapter.steps.map((step, index) => ({ chapter, step, index, total: chapter.steps.length })),
  )
}

/** Первый шаг главы в общей ленте. `-1` — главы нет (сняли по роли). */
export function startOf(entries: readonly TourEntry[], chapterId: string): number {
  return entries.findIndex((entry) => entry.chapter.id === chapterId)
}

