import type { UserRole } from '@/core/session'
import type { MascotPose } from '@/ui/mascot'

/**
 * Что рассказываем об устройстве приложения.
 *
 * Обучение разбито на главы по разделам приложения, глава — на шаги, шаг — на
 * одну возможность: карта мест, сбор группы встряской, «Живое фото». Так его
 * можно и пройти целиком при первом входе, и вернуться за одной главой из
 * шпаргалки, когда забылось, где что.
 *
 * Главы — единственный источник: из них собирается и обучение, и шпаргалка.
 * Появился раздел — допишите главу здесь и поднимите `TOUR_VERSION` в
 * `features/onboarding/state.ts`: тогда приветствие покажем ещё раз тем, кто
 * его уже закрыл.
 *
 * Иконки — только те, что есть в сабсете шрифта (`scripts/icon-names.txt`):
 * чужое имя вылезет на экран словом, а не картинкой. Позы маскота — из
 * `ui/mascot.ts`.
 *
 * Роли берём из `core/session/roles.ts` и не выдумываем: обещать семье кнопку,
 * которой у неё нет, хуже, чем промолчать.
 */

export interface TourStep {
  id: string
  mascot: MascotPose
  icon: string
  title: string
  body: string
  /** По шагам: что нажать, чтобы это сделать. */
  howto?: readonly string[]
  /** Под текстом — список разделов приложения. Только у шага «где что лежит». */
  sections?: boolean
  /** Шаг видит только эта роль. Пусто — шаг общий. */
  roles?: readonly UserRole[]
  /** Шаг только при включённом семейном и детском режиме. */
  familyOnly?: boolean
  /** Кнопка в конце шага: куда идти прямо сейчас. */
  action?: { label: string; route: string }
}

export interface Chapter {
  id: string
  /** Раздел приложения, о котором глава. */
  title: string
  /** Одна фраза: чем занят раздел. */
  summary: string
  icon: string
  /** Имя роута раздела. Модуля может не быть в сборке — тогда карточка без кнопки. */
  route: string | null
  /** Глава только для обучения: в шпаргалке её карточки нет. */
  tourOnly?: boolean
  steps: readonly TourStep[]
}

